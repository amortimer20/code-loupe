  await ready(page, 3);
  await page.getByRole('tab', { name:'Builder', exact:true }).click();
  await page.locator('[data-step="2"]').click();
  await page.locator('.builder-organize summary').click();
  await page.getByRole('button', { name:'Move up', exact:true }).click();
